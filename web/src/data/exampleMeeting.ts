/** 构造与真实生成一致的结果结构，让界面无需区分数据来源。 */
export function buildDemoResult(): GenerateResult {
  return {
    minutes: createDemoMinutes(),
    meta: {
      sourceType: 'text',
      fileName: null,
      charCount: DEMO_MEETING_TEXT.length,
      generatedAt: new Date().toISOString(),
      cached: false,
    },
  };
}

/** 用户改动任意字符后就不再是示例，不能再用内置结果冒充生成内容。 */
